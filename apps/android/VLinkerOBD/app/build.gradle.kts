// Release signing: keystore.properties (gitignored, one directory up from this file) holds the
// actual secrets. Loaded conditionally so a fresh checkout without that file — anyone other than
// the machine that generated the keystore — still configures and builds debug (and even
// assembleRelease, just unsigned) instead of failing Gradle's configuration phase outright.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

